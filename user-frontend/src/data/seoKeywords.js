export const getCourseKeywords = (courseId) => {
  const builder = COURSE_KEYWORD_MAP[courseId];
  if (!builder) {
    return [
      ...brandKeywords.slice(0, 10),
      ...pick(generalHseKeywords, 20),
      ...pick(locationKeywords, 10),
    ].join(", ");
  }
  // Deduplicate while preserving order
  const seen = new Set();
  return builder()
    .filter((k) => {
      const key = k.toLowerCase();
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .join(", ");
};

