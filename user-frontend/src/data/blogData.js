/**
 * Get a single post by its URL slug.
 * @param {string} slug
 * @returns {object|undefined}
 */
export function getPostBySlug(slug) {
  return blogPosts.find((post) => post.slug === slug);
}

/**
 * Get the top N featured posts (ordered by publishedDate desc).
 * @param {number} n
 * @returns {object[]}
 */
export function getFeaturedPosts(n = 3) {
  return blogPosts
    .filter((p) => p.featured)
    .sort((a, b) => new Date(b.publishedDate) - new Date(a.publishedDate))
    .slice(0, n);
}

/**
 * Get all posts belonging to a specific category.
 * @param {string} category
 * @returns {object[]}
 */
export function getPostsByCategory(category) {
  return blogPosts.filter((p) => p.category === category);
}

/**
 * Get N related posts for a given post ID (excludes self).
 * Falls back to most recent posts if relatedPosts array is empty.
 * @param {number} postId
 * @param {number} n
 * @returns {object[]}
 */
export function getRelatedPosts(postId, n = 3) {
  const post = blogPosts.find((p) => p.id === postId);
  if (!post) return [];

  if (post.relatedPosts && post.relatedPosts.length > 0) {
    const related = post.relatedPosts
      .map((id) => blogPosts.find((p) => p.id === id))
      .filter(Boolean)
      .slice(0, n);
    if (related.length >= n) return related;
  }

  // Fallback: same category, then most recent
  return blogPosts
    .filter((p) => p.id !== postId)
    .sort((a, b) => {
      const sameCategory =
        (a.category === post.category ? 1 : 0) -
        (b.category === post.category ? 1 : 0);
      if (sameCategory !== 0) return -sameCategory;
      return new Date(b.publishedDate) - new Date(a.publishedDate);
    })
    .slice(0, n);
}

/**
 * Get all unique category names.
 * @returns {string[]}
 */
export function getAllCategories() {
  return CATEGORIES;
}

/**
 * Get all unique tags across all posts.
 * @returns {string[]}
 */
export function getAllTags() {
  const tagSet = new Set();
  blogPosts.forEach((post) => {
    post.tags.forEach((tag) => tagSet.add(tag));
  });
  return Array.from(tagSet).sort();
}

/**
 * Format a date string into a human-readable format.
 * @param {string} dateStr ISO date string
 * @returns {string}
 */
export function formatDate(dateStr) {
  return new Date(dateStr).toLocaleDateString("en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}
